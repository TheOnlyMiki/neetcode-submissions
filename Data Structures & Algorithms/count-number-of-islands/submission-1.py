class Solution:
    def numIslands(self, grid: List[List[str]]) -> int:
        """
        题目：给定由 '1'（陆地）和 '0'（水）组成的二维网格，计算岛屿数量。
             岛屿由上下左右相邻的陆地连接而成，网格四周都被水包围。
        思路：DFS "淹没"法
        - 按顺序扫描每个格子，遇到一块还没处理过的陆地 '1'，说明发现了一个新岛屿，计数 + 1
        - 从这块陆地出发 DFS，把与它相连的所有陆地都改成 '0'（淹没）
        - 这样同一个岛屿的其他陆地之后不会再被重复计数
        本质是数图中连通分量的个数。
        例：grid = [["1","1","0","0"],
                    ["1","0","0","1"],
                    ["0","0","1","1"]]
            左上角 3 块是一个岛，右下角 3 块是一个岛 → 2
        时间复杂度 O(m · n)：每个格子最多被访问常数次（淹没后不会再进入 DFS）
        空间复杂度 O(m · n)：最坏情况（整个网格都是陆地）递归深度为 m · n

        小提示：
        - 直接把 grid 改成 '0' 来标记已访问，省去 visited 数组；
          如果题目不允许修改输入，就用 visited 集合或数组代替。
        - 递归深度可能很大：本题 m、n 最大 300，全是陆地时深度可达 90000，
          本地运行会超过 Python 默认递归上限 1000，可以用 BFS 或显式栈改写：
              def bfs(i, j):
                  queue = deque([(i, j)])
                  grid[i][j] = '0'                  # 入队时就标记，避免重复入队
                  while queue:
                      r, c = queue.popleft()
                      for a, b in [(1,0), (0,1), (-1,0), (0,-1)]:
                          nr, nc = r + a, c + b
                          if 0 <= nr < m and 0 <= nc < n and grid[nr][nc] == '1':
                              grid[nr][nc] = '0'
                              queue.append((nr, nc))
          BFS 要在"入队时"标记，而不是"出队时"，否则同一个格子可能被多次入队。
        - 并查集（Union-Find）也能解：把相邻陆地合并，最后数有多少个集合；
          适合"陆地动态增加、每次都要报告岛屿数"的变体（LeetCode 305）。
        - 同类网格 DFS 题：LeetCode 695（岛屿的最大面积，DFS 返回面积）、
          463（岛屿的周长）、130（被围绕的区域，从边界开始淹没）、
          417（太平洋大西洋水流，从两边边界反向 DFS）。
        """

        m, n = len(grid), len(grid[0])

        def dfs(i, j):
            """把与 (i, j) 相连的整片陆地都淹没成 '0'"""
            # 不越界且是陆地才处理；水或已淹没的格子直接返回
            if 0 <= i < m and 0 <= j < n and grid[i][j] != '0':
                # 淹没当前格子，标记为已访问
                grid[i][j] = '0'

                # 向上下左右四个方向继续淹没
                for a, b in [(1,0), (0,1), (-1,0), (0,-1)]:
                    dfs(i+a, j+b)

            return

        output = 0   # 岛屿数量

        # 逐个扫描格子
        for i in range(m):
            for j in range(n):
                # 遇到没被淹没的陆地：一定是一个新岛屿的第一块
                if grid[i][j] == '1':
                    output += 1

                    # 淹没整个岛屿，之后不会再重复计数
                    dfs(i, j)

        return output