class Solution:
    def pacificAtlantic(self, heights: List[List[int]]) -> List[List[int]]:
        """
        题目：m × n 的岛屿，heights[i][j] 为海拔。太平洋在左边和上边，大西洋在右边和下边。
             雨水可以从一个格子流向上下左右海拔"小于等于"它的相邻格子，边界格子可以直接流入相邻的海洋。
             返回所有既能流到太平洋、又能流到大西洋的格子坐标。
        思路：反向思考，从海洋往内陆"逆流而上"
        - 正向做法：对每个格子 DFS 看能否流到两个海洋，O((m·n)²)，会超时
        - 反向做法：从海洋边界出发，往海拔"大于等于"当前格子的方向走（水是从高往低流，反过来就是从低往高爬）
          · 从太平洋边界（第一列、第一行）出发能到达的格子 → 这些格子的水能流进太平洋
          · 从大西洋边界（最后一列、最后一行）出发能到达的格子 → 这些格子的水能流进大西洋
          · 两个集合的交集就是答案
        例：heights = [[1,2,2,3,5],
                       [3,2,3,4,4],
                       [2,4,5,3,1],
                       [6,7,1,4,5],
                       [5,1,1,2,4]]
            答案：[[0,4],[1,3],[1,4],[2,2],[3,0],[3,1],[4,0]]
        时间复杂度 O(m · n)：每个格子在每个集合中最多被访问一次
        空间复杂度 O(m · n)：两个集合 + 递归深度

        小提示：
        - "反向搜索"是这题的核心：多个起点（整条边界）+ 求"能到达哪里"，
          反过来从终点出发只需两次遍历，比从每个格子出发高效得多。
          类似的反向思路：LeetCode 130（被围绕的区域，从边界的 'O' 出发标记不会被包围的格子）。
        - 走的条件是 heights[x][y] >= heights[i][j]（逆流往高处走），方向千万别写反。
        - 四个角上的格子会被作为起点调用两次（行循环和列循环各一次），
          第二次进入时邻居都已访问过，只多一点点开销；
          也可以在调用前判断 if (i, j) not in visit 再调用。
        - 递归深度最坏为 m · n（本题最大 200 × 200 = 40000），
          本地运行可能超过 Python 默认递归上限 1000，可以改成 BFS：
          把所有太平洋边界格子一起入队做多源 BFS，大西洋同理。
        - 返回值也可以写成 list(map(list, pacific & atlantic))。
        """

        m, n = len(heights), len(heights[0])

        def dfs(i, j, visit):
            """
            从 (i, j) 逆流而上，把能到达的格子都加入 visit
            能到达的格子 = 水可以从那里流到 (i, j)，进而流进对应海洋
            """
            visit.add((i, j))

            for a, b in [(1,0),(0,1),(-1,0),(0,-1)]:
                x, y = i+a, j+b
                # 不越界、没访问过、且邻居海拔 >= 当前格子（水能从邻居流过来）
                if 0 <= x < m and 0 <= y < n and (x,y) not in visit and heights[x][y] >= heights[i][j]:
                    dfs(x, y, visit)

        pacific = set()    # 能流进太平洋的格子
        atlantic = set()   # 能流进大西洋的格子

        # ---------- 左右两列：左边接太平洋，右边接大西洋 ----------
        for i in range(m):
            dfs(i, 0, pacific)
            dfs(i, n-1, atlantic)

        # ---------- 上下两行：上边接太平洋，下边接大西洋 ----------
        for j in range(n):
            dfs(0, j, pacific)
            dfs(m-1, j, atlantic)

        # 两个海洋都能到达的格子
        return [[i,j] for i,j in (pacific & atlantic)]