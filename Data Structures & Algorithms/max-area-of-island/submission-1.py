class Solution:
    def maxAreaOfIsland(self, grid: List[List[int]]) -> int:
        """
        题目：给定由 1（陆地）和 0（水）组成的二维网格，返回最大岛屿的面积（陆地格子数）。
             岛屿由上下左右相邻的陆地连接而成；没有岛屿返回 0。
        思路：和 LeetCode 200（岛屿数量）同一个"DFS 淹没"框架，
             区别是 DFS 不再只负责淹没，还要返回这片岛屿的面积：
             面积 = 当前格子（1）+ 四个方向各自淹没到的面积之和
        例：grid = [[1,1,0],
                    [1,0,0],
                    [0,0,1]]
            左上角岛屿面积 3，右下角岛屿面积 1 → 3
        时间复杂度 O(m · n)：每个格子最多被淹没一次
        空间复杂度 O(m · n)：最坏（全是陆地）递归深度为 m · n

        小提示：
        - size = grid[i][j] 在这里一定等于 1（能进到这一步说明是陆地），
          直接写 size = 1 语义更清楚，也不依赖"陆地的值恰好是 1"。
        - 和 LeetCode 200 一样直接修改 grid 标记已访问；不能修改输入时改用 visited。
        - 递归深度最多 50 × 50 = 2500（本题 m、n <= 50），超过 Python 默认上限 1000，
          本地运行可能需要 sys.setrecursionlimit，或改成 BFS / 显式栈，统计出队的格子数即为面积。
        - 这种"DFS 返回子问题结果再累加"的写法，和二叉树里求节点数、求高度是同一个思路：
          网格中每个格子相当于一个有 4 个孩子的节点。
        - 同类题：LeetCode 463（岛屿的周长）、827（最大人工岛：把一个 0 变成 1 后的最大面积，
          先给每个岛编号并记录面积，再枚举每个 0 合并相邻的不同岛屿）。
        """

        m, n = len(grid), len(grid[0])

        def dfs(i, j):
            """淹没与 (i, j) 相连的整片陆地，并返回这片陆地的面积"""
            # 不越界且是陆地
            if 0 <= i < m and 0 <= j < n and grid[i][j] != 0:
                # 当前格子贡献面积 1
                size = grid[i][j]

                # 淹没，避免重复计算
                grid[i][j] = 0

                # 加上四个方向相连陆地的面积
                for a, b in [(1,0),(0,1),(-1,0),(0,-1)]:
                    size += dfs(i+a, j+b)

                return size

            # 越界、水或已淹没：面积为 0
            return 0

        best = 0   # 最大岛屿面积

        for i in range(m):
            for j in range(n):
                # 遇到没被淹没的陆地：新岛屿，计算面积并更新最大值
                if grid[i][j] == 1:
                    best = max(best, dfs(i, j))

        return best