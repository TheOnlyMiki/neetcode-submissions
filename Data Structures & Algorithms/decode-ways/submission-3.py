class Solution:
    def numDecodings(self, s: str) -> int:

        output = 0

        n = len(s)

        dp = [0] * (n + 1)
        dp[0] = 1

        for i in range(1, n+1):
            if s[i-1] != '0':
                dp[i] += dp[i-1]

            if i >= 2 and 10 <= int(s[i-2:i]) <= 26:
                dp[i] += dp[i-2]

        return dp[n]





























        """
        题目：字母按 'A' → "1"，'B' → "2"，…，'Z' → "26" 编码。给定只含数字的字符串 s，
             返回解码方法的总数。注意 "06" 不能解码成 'F'（"6" 和 "06" 不同）。
        思路：动态规划（和爬楼梯同一个结构：每次走 1 步或 2 步，只是每一步有条件）
        - 状态：dp[i] = 前 i 个字符 s[0 : i] 的解码方法数
        - 最后一步只有两种可能：
          · 最后 1 个字符单独解码：s[i-1] 不能是 '0'（'1' ~ '9' 都合法）
            → 方法数加上 dp[i-1]
          · 最后 2 个字符一起解码：s[i-2 : i] 必须在 "10" ~ "26" 之间（不能有前导 0）
            → 方法数加上 dp[i-2]
        - 初始值：dp[0] = 1，空字符串有一种解码方式（什么都不做），
          这样 dp[1]、dp[2] 都能用统一的转移公式计算
        例：s = "226"
            dp[0] = 1
            dp[1] = 1        "2"
            dp[2] = 2        "2 2"、"22"
            dp[3] = 3        "2 2 6"、"22 6"、"2 26"
        时间复杂度 O(n)，空间复杂度 O(n)

        小提示：
        - 开头的 if s[0] == '0': return 0 其实可以省略：
          s[0] 为 '0' 时 dp[1] = 0，之后两位数以 '0' 开头也不在 10 ~ 26，
          所有 dp 值都会是 0，最后自然返回 0。保留它则可以提前结束。
        - 判断两位数时用 10 <= int(...) <= 26，下界 10 同时排除了 "01" ~ "09" 这种带前导 0 的情况。
        - dp[i] 只依赖 dp[i-1] 和 dp[i-2]，可以用两个变量滚动，空间降到 O(1)：
              pre2, pre1 = 0, 1          # 对应 dp[i-2]、dp[i-1]，开始时 dp[0] = 1
              for i in range(1, len(s) + 1):
                  cur = 0
                  if s[i-1] != '0':
                      cur += pre1
                  if i >= 2 and 10 <= int(s[i-2:i]) <= 26:
                      cur += pre2
                  pre2, pre1 = pre1, cur
              return pre1
        - 遇到 "00"、"30" 这类无法解码的位置时，dp 会变成 0 并一直传递下去，最终结果为 0，
          不需要额外判断。
        - 进阶题 LeetCode 639（解码方法 II）：加入通配符 '*' 表示 1 ~ 9，
          转移相同，只是每种情况的系数要分类计算，且结果对 10^9 + 7 取模。
        """

        # 以 '0' 开头无法解码（可省略，见小提示）
        if s[0] == '0':
            return 0

        # dp[i]：前 i 个字符的解码方法数
        dp = [0] * (len(s)+1)
        dp[0] = 1   # 空串有一种解码方式，作为转移的基础

        for i in range(1, len(s)+1):
            # 最后一个字符 s[i-1] 单独解码：不能是 '0'
            if s[i-1] != '0':
                dp[i] += dp[i-1]

            # 最后两个字符 s[i-2 : i] 一起解码：必须在 10 ~ 26 之间
            if i >= 2 and 10 <= int(s[i-2:i]) <= 26:
                dp[i] += dp[i-2]

        return dp[len(s)]